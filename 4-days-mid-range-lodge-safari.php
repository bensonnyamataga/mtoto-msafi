<div class="tour-plan">
    <span class="tour-card1">03</span>
    <h4 class="tp-title">Day 3: Lake Manyara – Serengeti National Park</h4>
    <p class="tp-text">On the second day of your 4 Days Mid Range Tanzania Safari, we set out early for the world-famous Serengeti National Park. Known for its sweeping plains and rich wildlife, the Serengeti is home to the Big Five—lions, elephants, leopards, buffaloes, and rhinos—as well as many other fascinating species. As part of this mid-range safari, you’ll enjoy extensive game drives that showcase the incredible biodiversity and landscapes of the Serengeti. With some luck, you might witness the breathtaking spectacle of the Great Migration (seasonal), where wildebeest, zebras, and gazelles move in vast herds. At the end of the day, you’ll head to your mid-range camp or lodge for an overnight stay, surrounded by the sounds of the African wilderness.
    <ul class="tp-list">
        <li>Activity: Game drives.</li>
        <li>Meals Plan: Full Board</li>
    </ul>
    </p>
</div>

<div class="tour-plan">
