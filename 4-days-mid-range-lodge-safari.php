<div class="tour-plan">
    <span class="tour-card1">02</span>
    <h4 class="tp-title">Day 2: Moshi/Arusha – Lake Manyara National Park</h4>
    <p class="tp-text">Your 4 Days Mid Range Tanzania Safari begins with a morning pick-up from your hotel after breakfast. We head to Lake Manyara National Park, a scenic destination along the East African Rift Valley. The drive takes around two hours, and once there, you’ll encounter a unique ecosystem filled with wildlife. Lake Manyara is renowned for its large colonies of flamingos and other water birds, making this stop a fantastic introduction to Tanzania’s natural beauty. Along with birdlife, you’ll have the chance to spot elephants, giraffes, hippos, and even tree-climbing lions, a unique sight specific to this park. By late afternoon, we’ll drive to your comfortable lodge in Karatu, where you can relax and enjoy the evening.


    <ul class="tp-list">
        <li>Activity: Enroute game drives, Afternoon Game drives in Lake Manyara.</li>
        <li>Meals Plan: Lunch, Dinner</li>
