    <h4 class="tp-title">Day 1: Arrive In Tanzania</h4>
    <p class="tp-text">You will be picked up at the Kilimanjaro International Airport and transferred to your hotel in Moshi town; you will meet your guide who will brief you on your upcoming safari. All the basic information about your safari will be given to you by the safari guide.
