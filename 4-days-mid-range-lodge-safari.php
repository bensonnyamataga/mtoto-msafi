    <h4 class="tp-title">Day 4: Serengeti to Ngorongoro</h4>
    <p class="tp-text">After breakfast, we continue your 4 Days Mid Range Tanzania Safari with a drive to the Ngorongoro Crater, one of the most stunning natural wonders in Africa. The crater is a UNESCO World Heritage Site and is known as a microcosm of East African wildlife. <br><br> Upon descending into the crater, you’ll have the chance to see lions, rhinos, hippos, elephants, and a variety of birds within the crater’s unique ecosystem. This day offers ample wildlife viewing and photo opportunities in one of Tanzania’s most scenic landscapes. After a full day of exploration, we’ll return to your lodge in Karatu for a restful evening.
    <ul class="tp-list">
        <li>Activity: Game drives.</li>
        <li>Meals Plan: Full Board</li>
    </ul>
    </p>
</div>

