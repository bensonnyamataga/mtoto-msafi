   <h2 class="tab-title">Tour Itinerary</h2>
 <div class="tour-plan">
                    <span class="tour-card1">01</span>
                    <h4 class="tp-title">DAY 1 : Fly Zanzibar to Dar es Salaam – Mikumi National Park.
</h4>
                    <p class="tp-text">First ferry from Zanzibar depart 07:00 am, meet & greet in Dar Es Salaam at 08:30 am and drive to Mikumi & check-in at the camp and depart for afternoon game drive with hot lunch. Overnight Camp Bastian Mikumi. Take a very early morning flight from Zanzibar to Dar es Salaam where you will be met by your safari guide. <br> <br>
Your guide will meet you at the Dar es Salaam Airport and after assisting you with loading your luggage to your 4×4 safari jeep, you will start on your way to Mikumi National Park via the Dar es Salaam – Morogoro – Mbeya Highway. The drive from Dar es Salaam is a long drive that takes at least 5 – 6 hours depending on traffic so you will arrive in the early afternoon. <br> <br>
 As soon as you arrive at the Park’s Gate and after the quick paperwork, you will embark on your first game drives straightaway. With lunch taken at one of the picnic sites or at a Restaurant on the way to Mikumi, you will then spend the rest of the afternoon exploring the Mikumi National Park, hoping to see as much as possible in this same afternoon. <br> <br>
Mikumi National Park is part of the Mkata Floods plains within the Greater Selous Ecosystem and the park is rich in wildlife and bird life alike. You expect to see baboons, giraffes, lots of impalas, gazelles, buffaloes, lions, elephants ,kudus, and many other large animals. In the late afternoon you will retire to a nice tented camp (or a budget rest house in the park) depending on your budget. (Lunch & Dinner)


                </p>
                  </div>
                   <div class="tour-plan">
                    <span class="tour-card1">02</span>
                    <h4 class="tp-title">DAY 2 : Mikumi – Dar es Salaam – Fly back to Zanzibar.
</h4>
                    <p class="tp-text">This morning you will wake up very early in the morning for an early morning game drive before returning for breakfast at the lodge or rest house if staying inside the park. <br> <br>After breakfast you will continue with game drives for the better part of the morning until mid morning to noon when you will check out of the Park’s gate and drive back via Morogoro and Chalinze to Dar es Salaam. On arrival in the early evening you will take an evening flight back to Zanzibar Island where you will arrive in time for your dinner at your respective hotel / resort. Breakfast and Lunch included. (Breakfast & Lunch)<br> <br>

<strong>End of safari</strong>. It is important to note that this safari involves long drives of about 4 to 5 hours and sometimes more depending on the traffic floor and traffic police control along this busy highway to Mikumi National Park.
We can offer this 2 Days Mikumi National Park Safari from Zanzibar with a range of accommodations from budget, mid range to luxury tented camps located inside and outside the park’s boundaries.

                    
