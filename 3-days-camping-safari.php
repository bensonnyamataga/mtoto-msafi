                    <h4 class="tp-title">Day 1: : Moshi-Tarangire National Park
</h4>
                    <p class="tp-text">Depart for Tarangire National Park with packed lunch, approximately 4.5-hour drive from Moshi or 2 hours from Arusha to the Tarangire gate. Upon arrival, you will be introduced to an armed ranger who will take you on a guided walking safari for about 1.5-2 hours.

<br><br>This walk is a unique experience as part of your 3 Days Camping Safari, allowing you to see the nature and wildlife in the park in a completely different way. During this 3-day safari adventure, you'll encounter some of the remarkable wildlife that makes Tarangire so special. After your walking safari, your guide will take you to explore other parts of this famous National Park, well known for its large population of elephants. By late afternoon, your guide will exit the park and drive approximately 1 hour to the camp, where you’ll settle in for an unforgettable night under the stars, completing the day’s journey on your 3 Days Camping Safari..
                  
                    <ul class="tp-list">
		<li>Activity: 1.5- 2.0 hour Walking safari, Game drives.</li>
