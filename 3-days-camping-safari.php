                   <div class="tour-plan">
                    <span class="tour-card1">02</span>
                    <h4 class="tp-title">Day 2:Ngorongoro Crater</h4>
                    <p class="tp-text">After an early breakfast, you will depart with packed lunch for the Ngorongoro Crater as part of your 3 Days Camping Safari adventure. Upon entering the park, the road is steep, climbing up to the Ngorongoro Crater viewpoint, where your guide will stop to provide a briefing on the crater and allow you an amazing inspection of this world-renowned wonder from an incredible vantage point.

<br><br>This three-day safari experience includes an unforgettable journey into the largest unbroken crater in the world, home to over 25,000 animals, including the rare black rhino. Later, you’ll descend 610 meters into the crater floor for an amazing game drive and then, in the late afternoon, ascend and head to your campsite for dinner and overnight, ready for the next part of your 3 Days Camping Safari.
                      
                    <ul class="tp-list">
		<li>Activity: Crater floor game drives.</li>
