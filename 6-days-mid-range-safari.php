   <h2 class="tab-title">Tour Itinerary</h2>
 <div class="tour-plan">
        <span class="tour-card1">01</span>
        <h4 class="tp-title">DAY 1: Arrive In Tanzania</h4>
        <p class="tp-text">
            You will be picked up at the Kilimanjaro International Airport and transferred to your hotel in Moshi town; you will meet your guide who will brief you on your upcoming safari. All the basic information about your safari will be given to you by the safari guide.
        </p>
    </div>

    <div class="tour-plan">
        <span class="tour-card1">02</span>
        <h4 class="tp-title">DAY 2: Moshi / Arusha – Tarangire National Park</h4>
        <p class="tp-text">
            The excursion departs after breakfast. The first destination is Arusha Town, where we will make any last-minute purchases before departing on safari. Following that, we travel to Tarangire National Park for a wildlife drive and picnic lunch. Tarangire is famous for its large elephant population and baobab trees. It is the focal point of an annual migration of up to 3000 elephants, 25,000 wildebeest, and 30,000 zebras.
        </p>
    </div>

    <div class="tour-plan">
        <span class="tour-card1">03</span>
        <h4 class="tp-title">DAY 3: Lake Manyara National Park</h4>
        <p class="tp-text">
            After breakfast, we will drive to Lake Manyara National Park. This magnificent National Park is one of Tanzania’s most spectacular wildlife regions, consisting of a vast but shallow soda lake (encompassing two-thirds of the park) at the foot of the Great Rift Valley’s Western escarpment. The park’s diverse ecology attracts a broad range of wildlife, including one of Africa’s greatest populations of elephants; Manyara is also known for its tree-climbing lions and vast flocks of flamingos drawn to the lake by algae.
        </p>
    </div>

    <div class="tour-plan">
        <span class="tour-card1">04</span>
        <h4 class="tp-title">DAY 4 & 5: Serengeti National Park</h4>
        <p class="tp-text">
            After breakfast, head to Serengeti National Park, passing via Karatu’s stunning high rising farms and the Ngorongoro Conservation Area. Leaving the highlands behind, we descend into the Serengeti National Park, the heart of untamed Africa, with its boundless grasslands stretching into the horizon as far as the eye can see. Then head to the central park region, known as the Seronera area, one of the richest animal habitats in the park, containing the Seronera River, which offers a vital water source to this area and hence attracts wildlife representative of the majority of Serengeti species. Arrive in time for lunch and then have a wildlife drive in the Serengeti National Park in the afternoon.
        </p>
    </div>

    <div class="tour-plan">
        <span class="tour-card1">05</span>
        <h4 class="tp-title">DAY 6: Serengeti – Ngorongoro Crater</h4>
        <p class="tp-text">
            We will spend a day here for a wildlife drive before heading to Ngorongoro Crater and stopping at Olduvai Gorge on the way back. If you are interested in history and the Masai tribes enjoying on-route game, we will visit this intriguing archaeological site.
        </p>
    </div>

    <div class="tour-plan">
        <span class="tour-card1">06</span>
        <h4 class="tp-title">DAY 7: Ngorongoro Crater - Arusha/Moshi</h4>
        <p class="tp-text">
            Our final day begins very early in the morning with a picnic lunch and a 2000 ft. descent to the Crater floor by our 4-wheel drive vehicle for wildlife watching. Let us explore this Garden of Eden. Ngorongoro Crater is a massive and deep volcanic crater. The Crater floor is rich in grazing, wetlands, woodland, and permanent water, which explains why the species is so diverse and prolific. You will then drive to Arusha to make your onward arrangements.
        </p>
    </div>

