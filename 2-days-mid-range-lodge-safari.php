As part of this 2-day safari, you’ll see elephants, zebras, giraffes, hippos, and buffaloes, immersing yourself in the natural beauty and diversity that Lake Manyara has to offer. In the late afternoon, you’ll leave the park and head to a comfortable lodge in Karatu town, where you’ll enjoy an evening of relaxation after an exciting first day of your 2 Days Mid Range Safari in Tanzania.
