/* Jarga Tours: seamless, continuous right-to-left day trip carousel */
(function () {
  function initDayTrips() {
    const section = document.getElementById('jarga-day-trips');
    if (!section || section.dataset.jdReady === '1') return;
    section.dataset.jdReady = '1';

    const track = section.querySelector('.jd-track');
    const prev = section.querySelector('.jd-prev');
    const next = section.querySelector('.jd-next');
    if (!track) return;

    // Repeat the same five destinations to create a seamless visual loop.
    const originals = Array.from(track.querySelectorAll('.jd-slide'));
    if (!originals.length) return;
    const clones = originals.map(function (card) {
      const clone = card.cloneNode(true);
      clone.setAttribute('aria-hidden', 'true');
      clone.querySelectorAll('a, button, [tabindex]').forEach(function (el) {
        el.setAttribute('tabindex', '-1');
      });
      track.appendChild(clone);
      return clone;
    });

    const motionPreference = window.matchMedia('(prefers-reduced-motion: reduce)');
    const speed = 38; // pixels per second; increase to move faster
    let cycleWidth = 0;
    let lastFrame = null;
    let frameId = null;
    let isDragging = false;

    function measure() {
      // Distance between the first original and its first clone includes the gap.
      cycleWidth = clones[0].offsetLeft - originals[0].offsetLeft;
      if (cycleWidth > 0 && track.scrollLeft >= cycleWidth) {
        track.scrollLeft = track.scrollLeft % cycleWidth;
      }
    }

    function loop(time) {
      if (lastFrame === null) lastFrame = time;
      const delta = Math.min(time - lastFrame, 80);
      lastFrame = time;
      if (!motionPreference.matches && !isDragging && !document.hidden && cycleWidth > 0) {
        track.scrollLeft += speed * delta / 1000;
        if (track.scrollLeft >= cycleWidth) track.scrollLeft -= cycleWidth;
      }
      frameId = window.requestAnimationFrame(loop);
    }

    function advance(direction) {
      const gap = parseFloat(getComputedStyle(track).columnGap || getComputedStyle(track).gap) || 0;
      const distance = originals[0].getBoundingClientRect().width + gap;
      track.scrollLeft += direction * distance;
      if (track.scrollLeft >= cycleWidth) track.scrollLeft -= cycleWidth;
      if (track.scrollLeft < 0) track.scrollLeft += cycleWidth;
    }

    if (next) next.addEventListener('click', function () { advance(1); });
    if (prev) prev.addEventListener('click', function () { advance(-1); });

    track.addEventListener('pointerdown', function () { isDragging = true; });
    window.addEventListener('pointerup', function () { isDragging = false; });
    track.addEventListener('pointercancel', function () { isDragging = false; });
    track.addEventListener('scroll', function () {
      if (cycleWidth > 0 && track.scrollLeft >= cycleWidth) track.scrollLeft -= cycleWidth;
    }, { passive: true });
    window.addEventListener('resize', measure);

    // The original cards remain keyboard accessible; duplicates are decorative.
    // Respect visitors who request reduced motion.
    track.style.scrollBehavior = 'auto';
    track.style.scrollSnapType = 'none';
    measure();
    frameId = window.requestAnimationFrame(loop);
  }

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initDayTrips);
  } else {
    initDayTrips();
  }
})();
</script>
