                  <p>Mount Ol Doinyo Lengai trekking takes you to climb "The Mountain of God," as it is called in the Maasai language. Since ancient times, the Holy Lengai has been used by the Maasai for their prayers to their god known as Ngai.<br/> <br>
Standing at 2,878 meters above the Soda Ash Lake Natron, the Mountain of God is famous among the Maasai community that inhabits the area.
This mountain is situated in the Ngorongoro Highlands and the African Rift Valley. Lying just south of Lake Natron in the heart of Maasai country, it is locally regarded as a sacred mountain. It is about 230 kilometers northwest of Arusha, northern Tanzania.
<br/> <br>
<strong>Mount Oldoinyo Lengai Trekking Climbing Time:</strong>
A climb takes about 6-7 hours to reach the summit crater of this strato-volcano, which is 2,962 meters (9,718 feet) above sea level. The ascent is demanding due to the daytime heat, lack of water, steep and unsuitable slopes of ash, crumbly rocks, and considerable height gain. Normally, ascending to the summit starts early in the morning to reach the summit at sunrise.<br/>
While on the summit, one can sight the Soda Lake Natron, which is a good nesting site for different birds. The birds around the lake include flamingos, pelicans, geese, and more than 350 different types recorded to date.<br/> <br>
Looking north from its summit crater, the hot barren salt flats of Lake Natron stretch into the distance. To the eastern horizon is Mount Kilimanjaro. To the west, the forested escarpments and hills form the western slopes of the Rift Valley. <br> <br>
<strong>Other Activities Involved in Mount Ol Doinyo Lengai Trekking:</strong>
This area is also an ideal place for a walking safari escorted by Maasai guides with weapons. On the walking trip, tourists can sight wild animals and birds as well. Some of the animals include the Olive baboon, Vervet monkey, Hyena, Jackal, Grant’s gazelle, Impala, and Zebra, Giraffes, etc. The birds include Flamingos (the Lesser and Greater), Pelicans, Geese, Secretary birds, Larks, and others.<br/>
Nearby are the Maasai Villages that give you a chance to interact with them. And you can learn about their cultures, taboos, and traditions. A visit to the nearby waterfall and swimming in it is one of the activities within this area.</p><br/>
