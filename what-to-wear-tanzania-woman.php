      <h5>Weight Considerations</h5>
      <p>Domestic flights in Tanzania typically restrict checked luggage to 15kg (33lbs) and have strict size limitations (usually not exceeding 62 linear inches). Prioritize versatile, mix-and-match clothing items that can be worn multiple ways. Many lodges offer same-day laundry services (usually $1-2 per item), allowing you to pack lighter.</p>
