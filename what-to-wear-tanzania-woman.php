<!-- Expanded Cultural Considerations Section -->
<h2 class="tab-title">1. Cultural Considerations for Women's Clothing in Tanzania</h2>
<div class="tour-plan">
  <p class="tp-text">Understanding Tanzanian cultural norms will help you dress appropriately while feeling comfortable in different settings. Tanzania's dress code varies significantly between:</p>
  
  <div class="row">
    <div class="col-md-6">
      <div class="card outfit-card">
        <div class="card-header bg-white">
          <h5><i class="fas fa-city"></i> Urban Areas (Dar es Salaam, Arusha)</h5>
        </div>
        <div class="card-body">
          <ul>
            <li><strong>Business settings:</strong> Knee-length skirts or dresses with blouses</li>
            <li><strong>Casual wear:</strong> Jeans with modest tops are acceptable</li>
            <li><strong>Evening wear:</strong> Smart casual (no need for formal dresses)</li>
            <li><strong>Headscarves:</strong> Not required but appreciated near mosques</li>
            <li><strong>Shoes:</strong> Comfortable walking shoes for uneven sidewalks</li>
          </ul>
        </div>
      </div>
    </div>
    <div class="col-md-6">
      <div class="card outfit-card">
        <div class="card-header bg-white">
          <h5><i class="fas fa-umbrella-beach"></i> Zanzibar & Coastal Areas</h5>
        </div>
        <div class="card-body">
          <ul>
            <li><strong>Stone Town:</strong> Cover shoulders and knees (lightweight maxi dresses ideal)</li>
            <li><strong>Resorts:</strong> Standard swimwear acceptable at pools/private beaches</li>
            <li><strong>Beach cover-ups:</strong> Essential when leaving resort areas</li>
            <li><strong>Footwear:</strong> Water shoes for coral beaches, sandals for town</li>
            <li><strong>Evenings:</strong> Light shawl for cooler sea breezes</li>
          </ul>
        </div>
      </div>
    </div>
  </div>
  
  <div class="row mt-4">
    <div class="col-md-6">
      <div class="card outfit-card">
        <div class="card-header bg-white">
          <h5><i class="fas fa-mountain"></i> Highland Areas (Ngorongoro, Kilimanjaro)</h5>
        </div>
        <div class="card-body">
          <ul>
            <li><strong>Layering:</strong> Temperatures fluctuate dramatically (thermal base layers recommended)</li>
            <li><strong>Rain gear:</strong> Waterproof outer shell essential in rainy seasons</li>
            <li><strong>Footwear:</strong> Waterproof hiking boots with good traction</li>
            <li><strong>Headwear:</strong> Warm hat for early morning game drives</li>
            <li><strong>Gloves:</strong> Lightweight for chilly mornings</li>
          </ul>
        </div>
      </div>
    </div>
    <div class="col-md-6">
      <div class="card outfit-card">
        <div class="card-header bg-white">
          <h5><i class="fas fa-tree"></i> Safari & Rural Villages</h5>
        </div>
        <div class="card-body">
          <ul>
            <li><strong>Modesty:</strong> Even in heat, avoid tank tops/short shorts</li>
            <li><strong>Colors:</strong> Neutral tones preferred (khaki, olive, beige)</li>
            <li><strong>Fabric:</strong> Quick-dry materials for comfort</li>
            <li><strong>Coverage:</strong> Long sleeves/pants protect from sun and insects</li>
            <li><strong>Footwear:</strong> Closed-toe shoes for bush walks</li>
          </ul>
        </div>
      </div>
    </div>
  </div>
  
  <div class="packing-tip mt-4">
    <i class="fas fa-hands-helping"></i>
    <div>
      <h5>Respecting Local Customs</h5>
      <p>When visiting Maasai villages or other cultural communities, women should dress particularly conservatively. A long skirt (or kanga wrap) with a modest top shows respect. Some villages may request you remove shoes before entering homes. Observe what local women are wearing and follow their lead - this attention to cultural sensitivity often leads to warmer welcomes and more meaningful interactions.</p>
    </div>
  </div>
</div>

