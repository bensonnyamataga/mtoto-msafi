<h2 class="tab-title">2. Essential Packing List for Women Traveling to Tanzania</h2>
<div class="tour-plan">
  <p>This comprehensive packing list has been refined through feedback from hundreds of female travelers. It accounts for all climate zones and activities you might encounter:</p>
  
  <div class="packing-list">
  <h4>Tops (7-9 total)</h4>
  <ul class="tight-bullets">
    <li>3-4 short-sleeve moisture-wicking shirts</li>
    <li>2 long-sleeve sun protection shirts (UPF 50+)</li>
    <li>1 lightweight sweater/fleece</li>
    <li>1 smart casual top for dinners</li>
    <li>1 thermal base layer (for high altitude)</li>
    <li>1-2 tank tops (for layering under shirts)</li>
  </ul>

  <h4>Bottoms (5-6 total)</h4>
  <ul class="tight-bullets">
    <li>2 convertible hiking pants (zip-off legs)</li>
    <li>1 lightweight trekking skirt (with shorts underneath)</li>
    <li>1 pair of comfortable jeans/trousers</li>
    <li>1 loose-fitting linen pants for coastal areas</li>
    <li>1 pair of thermal leggings</li>
  </ul>

  <h4>Footwear (3-4 pairs)</h4>
  <ul class="tight-bullets">
    <li>Sturdy hiking shoes (broken in before trip)</li>
    <li>Comfortable walking sandals (with backstrap)</li>
    <li>Water shoes (for beaches/reef walking)</li>
    <li>Lightweight sneakers (optional for towns)</li>
    <li>Camp shoes/slippers (for lodges)</li>
  </ul>

  <h4>Accessories</h4>
  <ul class="tight-bullets">
    <li>Wide-brimmed hat with chin strap</li>
    <li>UV protection sunglasses (polarized)</li>
    <li>Microfiber travel towel</li>
    <li>Reusable water bottle (insulated)</li>
    <li>Headlamp with red light setting</li>
    <li>Lightweight daypack (20-30L)</li>
  </ul>

