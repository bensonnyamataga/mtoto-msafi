                    <span class="tour-card1">02</span>
                    <h4 class="tp-title">Day 2
Lake Manyara National Park
</h4>
                    <p class="tp-text">After breakfast, we head to Moshi town for optional shopping and currency exchange. Following this, we proceed through the Masai steppe and the Great Rift Valley to Lake Manyara National Park. After registering at the park gate, we embark on a short game drive before enjoying a hot lunch at the lodge or tented camp. Later in the afternoon, we embark on a sunset game drive, encountering diverse wildlife such as elephants, giraffes, zebras, and the famed tree-climbing lions. We also marvel at the array of aquatic birds by the lake. Afterward, we return to the lodge for dinner and overnight <br/>. All meals included.</p>
                  </div>
