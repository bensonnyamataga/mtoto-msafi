                    <h4 class="tp-title">Day 3
Olduvai Gorge - Serengeti National Park
</h4>
                    <p class="tp-text">This morning, we depart early for Serengeti National Park, the oldest and largest park in Tanzania. En route, we make a brief stop at Olduvai Gorge, where significant discoveries of human fossils were made. Continuing to Serengeti via Naabi Hill gate, we enjoy game drives with a picnic lunch. Serengeti's vast plains are home to a variety of wildlife, including zebras, elephants, baboons, and more. We then arrive at the Camp for dinner and overnight, immersing ourselves in an 'out of Africa' experience.</p>
