            <p>The Great Wildebeest Migration - the annual migration of giant herds of grazers across Northern Tanzania and Kenya is a truly spectacular event. Over two million wildebeest, zebras and gazelles move through the Serengeti and Masai Mara ecosystems in search of green pasture, in a regular pattern. This is surely one of the greatest wonders of the natural world.</p> <br>
                              <h2>Great Migration Safari Holidays: the basics </h2>
                              <p>You can witness the Great Migration in Tanzania throughout the year, as the wildebeests migrate in a circular pattern around the Serengeti National Park, making it an ongoing event. Below, we'll explore where the wildebeests typically are at different times of the year.
<br/><br>
The Great Wildebeest Migration rarely extends into the Masai Mara in Kenya. The herds only venture there as an extension of their grazing lands in the northern region of Tanzania if they require fresh pastures. In Kenya, you can observe the migration only for a few months of the year when they move towards the border. However, during this time, most of the herds still remain in the northern parts of the Serengeti.
</p> 
         
                             <h2>The Annual Migration overview: the best times to visit The Wildebeest in Africa </h2>      
                             <p><h4>July – October:</h4> This is when the wildebeest are in the northern Serengeti plains, and you have a chance of seeing up to thousands crossing the great Mara River. As the sight of the wildebeest crossing the so dramatic, it is considered by many the most desirable time to see the migration.<br/><br>
<h4>December – March:</h4> Currently the wildebeest are in the southern area of the Serengeti, more specifically in Ndutu which is actually in the Ngorongoro Conservation Area, and it is calving season. Along with the river crossings, this is a real highlight of the wildebeest’s journey and a fabulous time to see the herds congregate on the dramatic sweeping plains of the south. February is the only time of year when you are almost guaranteed to see the big herds all together as they always come south for calving season. <br/><br>
<h4>The rest of the year:</h4> In November, April, May and June the migration is “in between” locations and as such these months are slightly transitional times to see the herds. November is the short rains, April and May are the long rains and as such the grass is green in these months across the Serengeti, so the wildebeest are more dispersed than in the prime time of July – October and December – March. Thus, you don’t get as many of those condensed big herds which people get excited about! 
<br/><br>
Although we try to be as comprehensive as possible, something that is quite difficult to express on paper is a lot easier to explain over the phone, so please do just give us a call for a simple overview of the Migration's route. </p>
<h4>THE WILDEBEEST MIGRATION: A GUIDE TO THE GREAT MIGRATION AFRICA</h4><br/><br>
<h5>
Great Migration Map - Kenya Migration and Serengeti Migration</h5>
<p>Please refer to our migration map of the Tanzania/Kenya border and the path of the Mara River through each country. A common misconception is that the river serves as a border between the two countries, but as depicted on the map, this is not accurate! The wildebeests typically cross the river not from Tanzania into Kenya, but rather between Kogatende and the Lamai Wedge (Tanzania to Tanzania), or within Kenya from the Masai Mara into the Masai Mara (Kenya to Kenya).</p>
<br/><br>
<h5>Great Migration Safari Holidays: Where to Stay for The Great Migration in Tanzania</h5>
<p>If you're looking to safari amidst the heart of the Great Migration of wildebeest and zebra, the best option is to book one of the Serengeti's renowned mobile camps. These camps are set up at specific locations throughout the year and often relocate two or three times annually based on the movement of the herds.
<br/><br>
Two mobile camps, in particular, stand out for their dedication to following the herds - Nomad Tanzania's Serengeti Safari Camp and &Beyond's Serengeti Under Canvas. These operations are truly mobile and positioned near or within the herds year-round, moving to more than two locations, unlike most other mobile camps. Additionally, camps like Alex Walker's Serian, Asilia's Olakira, Ubuntu, and Kimondo relocate twice a year, providing excellent mobile experiences from July to November and from December to March. These camps are closed for the remainder of the year.
<br/><br>
If embarking on a mobile safari seems too adventurous, the Serengeti offers several permanent lodges that provide all the comforts you need while offering excellent locations to witness the herds during your Tanzania safari. Below is an overview of the herd movements and the best permanent lodges to stay at for each time of year.</p><br>
	
<h4>The Annual Great Wildebeest Migration Dates & Seasons: A Month-by-Month Explanation of the Serengeti Wildebeest Migration</h4>
<p><h5>December to March:</h5>
During this period, the vast grass plains of the Southern Serengeti extend into the Ngorongoro Conservation Area. From December to March, the Serengeti Migration gathers in large herds around Lake Ndutu in the Ngorongoro Conservation Area. As the herds reach the area, they split up and spread out, leaving wildebeest herds as far as the eye can see. Ndutu Lodge and Kusini are the only permanent lodges in the area, with Kusini being ideal towards the end of the period, while Ndutu Lodge operates throughout. Asilia's Dunia Camp is also a good option at the beginning of December and again when the herds push north in March. For further details, see our month-by-month blog posts for December, January, February, and March.
<br/><br>
<h5>April to May:</h5>
This period marks the rainy season in Tanzania. The Wildebeest migration moves north into the plains of the southern Serengeti, with front runners stretching out to the Western Corridor and the center of the park at Seronera. Asilia's Dunia Camp is a great option during this time, as are any of the central Serengeti hotels such as the Serena or Sopa. Some early herds may have pushed up to the Grumeti River Camp, Kirawira, and Mbalageti Lodge area of the Western Corridor. For further details, see our month-by-month blog posts for April and May.
<br/><br>
<h5>June and July:</h5>
June marks the mating season for the herds, which can be very noisy if many are together. By June, wildebeest herds are spread from the Western Corridor through the heart of the park. One group tends to head west into the Western Corridor and crosses the Grumeti River before entering the exclusive Singita Grumeti Reserves. <br> <br> The other herds head directly north of the Serengeti, passing through Seronera, Lobo, and up to the Bologonja river area near the Eastern border with the Loliondo reserve at Kleins. At this time, herds can be anywhere from the Western Corridor to the Eastern side of the park. Splinter herds will break from the main herds, covering huge areas in their search for fresh grasses. <br> <br>For the Western Corridor, recommended accommodations include Grumeti River Camp, Faru Faru, Sasakwa, Sabora, Singita Explore, Mbalageti Lodge, and Kirawira, while some herds may have pushed up as far as Migration camp in the Northern Lobo area. Late July will see good herds at any of the Kogatende permanent lodges, with Serengeti Lamai and Sayari Camp being recommended towards the end of July. For further details, see our month-by-month blog posts for June and July.
<br/><br> 
<h5>August through October:</h5>
During this period, the herds are in the Northern Serengeti at Kogatende, as well as in Kenya’s Masai Mara, with river crossings often happening daily. Kogatende is an exceptional destination with only a fraction of the visitor numbers compared to the Mara. The herds move in a circular fashion throughout these months, offering fantastic viewing opportunities. <br> <br>Contrary to common misconceptions, the herds do not only head north from June and stay in Kenya until October. Instead, they move in both directions throughout the day. Excellent opportunities to witness river crossings are available in Tanzania due to the numerous crossing points along the Mara River. For further details, see our month-by-month blog posts for August, September, and October.
<br/><br>
<h5>November:</h5>
In late October and November, the herds start their second Great Migration south towards the fertile lands of the Ndutu plains. This can be a tricky time to catch the mega herd as it covers vast distances every day. However, by the beginning of December, the herds return to Ndutu to calve, starting the process anew. <br> <br>It's important to note that wildebeests are not the most predictable animals, and the Migration is entirely dependent on rain, with the herds constantly searching for fresh grasses. Thus, predicting their whereabouts during any particular week is challenging, and choosing a camp located in the 'right' area for the time of year increases the chances of witnessing the Migration. However, there are no guarantees.</p>
