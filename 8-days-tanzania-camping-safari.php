  <p class="tp-text">
    After breakfast, depart for Tarangire National Park, famous for its vast herds of elephants and towering baobab trees. Spend the day on a game drive, spotting wildlife such as lions, leopards, and giraffes. In the evening, camp inside the park.
    <ul class="tp-list">
      <li>Full-day game drive in Tarangire</li>
      <li>Observe elephants and baobabs</li>
      <li>Overnight camping in Tarangire</li>
    </ul>
  </p>
