<div class="tour-plan">
  <span class="tour-card1">03</span>
  <h4 class="tp-title">Day 3: Tarangire to Serengeti National Park</h4>
  <p class="tp-text">
    On the third day on this 8 Days camping safari,After an early breakfast, travel to the iconic Serengeti National Park via the Ngorongoro Conservation Area. Upon arrival, enjoy an afternoon game drive before setting up camp in the heart of the Serengeti, surrounded by the sounds of wildlife.
    <ul class="tp-list">
      <li>Scenic drive through Ngorongoro</li>
      <li>Afternoon game drive in Serengeti</li>
      <li>Overnight camping in Serengeti</li>
    </ul>
  </p>
</div>

