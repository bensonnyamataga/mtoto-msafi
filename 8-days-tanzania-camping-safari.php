  <h4 class="tp-title">Day 5: Serengeti to Ngorongoro Crater Rim</h4>
  <p class="tp-text">
    This 8 Days camping safari you will take a game drive in Serengeti, journey to the Ngorongoro Crater. Enjoy a scenic drive with panoramic views of the crater below. In the evening, set up camp on the crater rim.
    <ul class="tp-list">
      <li>Morning game drive in Serengeti</li>
      <li>Drive to Ngorongoro Crater</li>
      <li>Overnight camping on the crater rim</li>
