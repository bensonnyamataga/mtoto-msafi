  <span class="tour-card1">04</span>
  <h4 class="tp-title">Day 4: Full Day in Serengeti National Park</h4>
  <p class="tp-text">
    Spend a full day on a thrilling game drive in the Serengeti. Witness the Great Migration (seasonal) or encounter predators like lions, leopards, and cheetahs. After a picnic lunch, continue exploring this vast wilderness before returning to camp.
    <ul class="tp-list">
      <li>Morning and afternoon game drives</li>
      <li>Possibility to witness the Great Migration</li>
      <li>Overnight camping in Serengeti</li>
    </ul>
  </p>
</div>

