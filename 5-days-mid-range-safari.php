    <h4 class="tp-title">Day 3: Serengeti National Park
    </h4>
    <p class="tp-text">
    After breakfast, we depart for the world-renowned Serengeti National Park, one of the key highlights of your 5 Days Mid Range Tanzania Safari. Known for its vast plains and incredible wildlife, the Serengeti is home to the Big Five—lions, elephants, leopards, buffaloes, and rhinos. Throughout the day, you’ll enjoy thrilling game drives in search of these iconic species, as well as the seasonal Great Migration (timing-dependent), where wildebeest and zebras move in huge herds across the plains. You’ll spend the night at a mid-range camp or lodge in the Serengeti, surrounded by the sights and sounds of the African wilderness.
        <ul class="tp-list">
