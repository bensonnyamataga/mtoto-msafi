    <h4 class="tp-title">DAY 2 : Full Day Selous Game Reserve.</h4>
    <p class="tp-text">After your first night in Selous, awake early to a dawn chorus and spectacular views from your room (“banda”).<br><br> After a quick cup of tea or coffee, head into the reserve as dawn breaks for a full day game drive in a specially modified safari vehicle with a professional guide, in which you should see and learn much about a large number of animals, including all the great favourites – lion, elephant, giraffe, buffalo, zebra – and all the other major species including the now rare African hunting dog. <br><br>
Great variety of bird species. Wonderful scenery, with varied topography: wetlands, dry grassland, light acacia forest and higher ground with long views to far-off mountains. Packed lunch and time to rest. Your guide will select a location with shade and water nearby to watch animals coming to drink – a place with a clear view all round so that no predator can creep up unseen! Back to the lodge by 6.30 for sunset and dinner when you’re ready. Overnight at Selous River Camp<strong>(breakfast, lunch & dinner)</strong>
</p>
    
