    <p class="tp-text">Start Your Unique 3-Days Selous Game Reserve Tour by  flight to the UNESCO World Heritage site of Selous Game Reserve will leave Zanzibar at 0930 am and takes one hour. You will be met at the airstrip in Selous by your Selous River Camp guide who will transfer you to the lodge. <br><br>
En route, you will enjoy your first experience of this incredible and diverse reserve. After lunch, Sunset cruise on our comfortable riverboat, looking at hippos, crocodiles and birds, and enjoying the spectacular sunset over this enormous river. Overnight at Selous River Camp <strong>(Lunch & Dinner)</strong>
