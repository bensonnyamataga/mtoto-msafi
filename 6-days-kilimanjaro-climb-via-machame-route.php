   <h2 class="tab-title">Tour Itinerary</h2>
   <div class="tour-plan">
                    <span class="tour-card1">0</span>
                    <h4 class="tp-title">Day 0: Arrival Day and Pre-Trek Briefing
</h4>
                    <p class="tp-text">Arrival: Optional airport transfers from Kilimanjaro Airport or Arusha Airport to your hotel in Moshi.<br/>
Activity: Pre-trek briefing at your hotel. Arrive at least one day before the trek starts to review your equipment and rent any necessary gear.</p>
                  </div>
 <div class="tour-plan">
                    <span class="tour-card1">01</span>
                    <h4 class="tp-title">Day 1: Moshi / Machame Gate to Machame Camp
</h4>
                    <p class="tp-text">

Drive: Transfer from Arusha to Machame Gate, passing through the village of Machame.
Trek: Begin the hike through the rainforest on a winding trail up a ridge. The lower elevations can be muddy and slippery; gaiters and trekking poles are recommended.
<ul>
	<li>Elevation: 1,830 meters (6,000 feet) to 3,050 meters (9,950 feet)</li>
	<li>Distance: 11 kilometers (7 miles)</li>
	<li>Hiking Time: 5-6 hours</li>
	<li>Habitat: Montane Forest</li>
	<li>Meals: Lunch and Dinner</li>
</ul></p>
                  </div>
                  <div class="tour-plan">
                    <span class="tour-card1">02</span>
                    <h4 class="tp-title">Day 2: Machame Camp to Shira Camp
</h4>
                    <p class="tp-text">

Trek: Leave the rain forest and continue on an ascending path, crossing a valley and climbing a steep rocky ridge. The route turns west and follows a river gorge to Shira Camp.
<ul>
	<li>Elevation: 3,050 meters (9,950 feet) to 3,850 meters (12,600 feet)</li>
	<li>Distance: 5 kilometers (3 miles)</li>
	<li>Walking Time: 4-5 hours</li>
	<li>Habitat: Moorland</li>
	<li>Meals: Breakfast, Lunch, and Dinner</li>
</ul></p>
                  </div>
                   <div class="tour-plan">
                    <span class="tour-card1">03</span>
                    <h4 class="tp-title">Day 3: Shira Camp to Lava Tower to Barranco Camp
</h4>
                    <p class="tp-text">

Trek: From the Shira Plateau, hike east up a ridge, passing the junction towards Kibo Peak. Continue to the Lava Tower (4,650 meters / 15,250 feet), then descend to Barranco Camp. This day helps with acclimatization.
<ul>
	<li>Elevation: 3,850 meters (12,600 feet) to 4,000 meters (13,000 feet)</li>
	<li>Distance: 10 kilometers (6 miles)</li>
	<li>Walking Time: 5-6 hours</li>
	<li>Habitat: Semi-desert</li>
	<li>Meals: Breakfast, Lunch, and Dinner</li>
</ul></p>
                  </div>
                   <div class="tour-plan">
                    <span class="tour-card1">04</span>
                    <h4 class="tp-title">Day 04:Barranco Camp to Barafu Camp
</h4>
                    <p class="tp-text">Trek: Ascend the Barranco Wall (4,250 meters / 13,900 feet), traverse the Karanga Valley (4,050 meters / 13,250 feet), and continue up to Barafu Camp. Enjoy views of the summit from different angles.
<ul>
	<li>Elevation: 4,000 meters (13,000 feet) to 4,700 meters (15,350 feet)</li>
	<li>Distance: 9 kilometers (6 miles)</li>
	<li>Hiking Time: 6-8 hours</li>
	<li>Habitat: Alpine Desert</li>
	<li>Meals: Breakfast, Lunch, and Dinner</li>
</ul></p>
                  </div>
                    <div class="tour-plan">
                    <span class="tour-card1">05</span>
                    <h4 class="tp-title">Day 5: Barafu Camp to Summit to Mweka Camp
</h4>
                    <p class="tp-text">

Trek: Depart from Barafu Camp in the early morning (midnight to 2 am) to summit via the Rebmann and Ratzel glaciers. Ascend through scree to Stella Point on the crater rim, then continue to Uhuru Peak. After summiting, descend to Mweka Camp, stopping at Barafu for lunch. Gaiters and trekking poles are useful for the descent.
<ul>
	<li>Elevation: 4,700 meters (15,350 feet) to 5,895 meters (19,340 feet) and descend to 3,090 meters (10,150 feet)</li>
	<li>Distance: 5 kilometers (3 miles) up / 13 kilometers (8 miles) down</li>
	<li>Hiking Time: 5-7 hours up / 5-6 hours down</li>
	<li>Habitat: Stone scree and ice-capped summit</li>
	<li>Meals: Breakfast, Lunch, and Dinner</li>
</ul></p>
                  </div>
                    <div class="tour-plan">
                    <span class="tour-card1">06</span>
                    <h4 class="tp-title">Day 6: Mweka Camp to Mweka Gate to Hotel
</h4>
                    <p class="tp-text">

Trek: Descend from Mweka Camp to Mweka Gate to collect your summit certificate. Expect wet and muddy conditions at lower elevations; gaiters and trekking poles are helpful. Dress in light clothing but keep rain gear handy.
<ul>
	<li>Elevation: 3,090 meters (10,150 feet) to 1,680 meters (5,500 feet)</li>
	<li>Distance: 10 kilometers (6 miles)</li>
	<li>Hiking Time: 3-4 hours</li>
	<li>Habitat: Forest</li>
	<li>Meals: Breakfast</li>
	<li>Transfer: Return to your hotel in Arusha via a Company Name vehicle.</li>
</ul>
</p>
