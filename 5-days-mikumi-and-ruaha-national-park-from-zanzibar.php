Ruaha National Park, the less visited South, lies deep in the South with its striking, rugged landscapes and abundant wildlife. <br><br>
The great Ruaha River that provides life to the park, flows through the eastern side of the park and is home to hippos, crocodiles and the bird count is over 400 species of birds such as Racket Tailed Roller, Pale billed Hornbill, Shelley’s Sunbird and Hoopoes. <br><br>
 Ruaha providing home to one of Tanzania’s largest elephant populations, famous for pride of lions, giraffe, grant’s gazelles, Leopard, Cheetah, Zebra, Giraffe, Buffallo etc and rare or endangered animals such as Sable Antelope, Greater Kudu & Roan Antelope.<br><br>

Mikumi National Park ,”The mini Serengeti” The open horizons and abundant wildlife of the Mkata Floodplain the popular center piece of Mikumi. Commonly seen animals are Elephant, Giraffe, Zebra, Antelope, Wildebeest, Eland, Crocodile, Hippo, Baboon, if you are lucky, won’t miss to see Lion & very lucky to see a Leopard, over 300 spices of birds are seen are saddle bill stork, hammer kop, malachite kingfisher, lilac breasted roller, yellow throated long claw, battler eagle etc. Another attraction: the Hippo Pools, where you can watch hippos wallowing and snorting at close range

