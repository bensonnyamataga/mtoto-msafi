                <p>Monitor bird alarm calls (especially hornbills and guinea fowl)</p>
              </div>
              <div class="season-item">
                <i class="fas fa-search"></i>
                <p>Look for tracks near muddy areas or sandy riverbanks</p>
              </div>
              <div class="season-item">
                <i class="fas fa-tree"></i>
                <p>Scan specific tree species favored by leopards (sausage, acacia)</p>
              </div>
              <div class="season-item">
                <i class="fas fa-wind"></i>
                <p>Observe wind direction to approach downwind without detection</p>
              </div>
