									   	<li>Distance: 13 km</li>
									   	<li>Hiking Time: 4-6 hours</li>
									   	<li>Habitat: Heath</li>
									   </ul>

Descending from the summit, we retrace our steps through the heath zone to Miriakamba Huts.
<ul>
