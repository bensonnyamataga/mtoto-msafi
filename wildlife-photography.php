                  <h4 class="mt-4">Advanced Techniques</h4>
                  <div class="photo-tip">
                    <i class="fas fa-sun"></i>
                    <div>
                      <h5>Backlighting Magic</h5>
                      <p>Shoot during golden hour with animals backlit for dramatic rim lighting. Use exposure compensation +1 to +2 stops to avoid silhouettes.</p>
                    </div>
                  </div>
                  <div class="photo-tip">
                    <i class="fas fa-tint"></i>
                    <div>
                      <h5>Rainy Day Strategies</h5>
                      <p>Overcast light is perfect for even exposures. Capture water droplets on fur at 1/500s shutter speed. Use higher ISO to compensate for low light.</p>
                    </div>
                  </div>
                  <div class="photo-tip">
                    <i class="fas fa-moon"></i>
                    <div>
                      <h5>Low Light Solutions</h5>
                      <p>For dusk/dawn shots: Open aperture to f/2.8-f/4, increase ISO to 3200-6400, use lens stabilization, and brace against vehicle.</p>
                    </div>
