                <!-- Section 4: Ethical Wildlife Photography -->
                <h2 class="tab-title">4. Ethical Wildlife Photography Practices</h2>
                <div class="tour-plan">
                  <p>Responsible photography ensures animal welfare and authentic behavior:</p>
                  
                  <div class="row">
                    <div class="col-md-6">
                      <div class="card settings-card">
                        <div class="card-header bg-white">
                          <h5><i class="fas fa-check-circle"></i> Do's</h5>
                        </div>
                        <div class="card-body">
                          <ul>
                            <li>Maintain safe distances (use zoom instead)</li>
                            <li>Respect animal behavior (don't interrupt hunting/feeding)</li>
                            <li>Follow guide instructions at all times</li>
                            <li>Shoot from vehicles when possible</li>
                          </ul>
                        </div>
                      </div>
                    </div>
                    <div class="col-md-6">
                      <div class="card settings-card">
                        <div class="card-header bg-white">
                          <h5><i class="fas fa-times-circle"></i> Don'ts</h5>
                        </div>
                        <div class="card-body">
                          <ul>
                            <li>Never bait or call animals</li>
                            <li>Avoid flash photography with nocturnal animals</li>
                            <li>Don't remove vegetation for "better" shots</li>
                            <li>Never approach animals on foot (except in designated areas)</li>
                          </ul>
                        </div>
                      </div>
                    </div>
                  </div>
                  
                  <h4 class="mt-4">The Photographer's Code</h4>
                  <div class="alert alert-warning">
                    <i class="fas fa-exclamation-triangle"></i> <strong>Remember:</strong> The welfare of the subject always comes before getting the shot. If an animal shows signs of stress (changed behavior, vocalizations, staring), back off immediately.
                  </div>
                  
                  <div class="photo-tip">
                    <i class="fas fa-calendar-alt"></i>
                    <div>
                      <h5>Seasonal Considerations</h5>
                      <p>Dry season (June-October) offers better visibility but more vehicle traffic. Green season (November-May) provides dramatic skies and newborn animals but challenging light.</p>
