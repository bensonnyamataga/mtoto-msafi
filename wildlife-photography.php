                <!-- Section 3: Composition Techniques -->
                <h2 class="tab-title">3. Wildlife Photography Composition</h2>
                <div class="tour-plan">
                  <p>Transform ordinary safari shots into extraordinary images with these composition techniques:</p>
                  
                  <h4 class="tp-title"><i class="fas fa-rule-of-thirds"></i> Rule of Thirds with a Twist</h4>
                  <p>While the classic rule of thirds works, try these variations for wildlife:</p>
                  <ul>
                    <li><strong>Eye placement:</strong> Position the animal's eye at the top intersection point</li>
                    <li><strong>Directional space:</strong> Leave more space in front of moving animals</li>
                    <li><strong>Environmental context:</strong> Use lower third for habitat when appropriate</li>
                  </ul>
                  <img src="assets/img/tanzania-photo-safari.jpg" alt="Wildlife photography composition examples" class="img-fluid mt-3">
                  
                  <h4 class="tp-title mt-4"><i class="fas fa-layer-group"></i> Layering for Depth</h4>
                  <p>Create three-dimensional images by incorporating:</p>
                  <div class="row">
                    <div class="col-md-6">
                      <ul>
                        <li>Foreground elements (grass, branches)</li>
                        <li>Midground subject (the animal)</li>
                        <li>Background context (habitat, other animals)</li>
                      </ul>
                    </div>
                    <div class="col-md-6">
                      <ul>
                        <li>Atmospheric perspective (dust, haze)</li>
                        <li>Leading lines (rivers, tree lines)</li>
                        <li>Frame-within-frame (tree openings)</li>
                      </ul>
                    </div>
                  </div>
                  
                  <h4 class="tp-title mt-4"><i class="fas fa-expand"></i> Perspective Variation</h4>
                  <p>Avoid shooting everything from eye level. Mix these angles:</p>
                  <div class="tech-grid">
                    <div class="tech-item">
                      <i class="fas fa-arrow-up"></i>
                      <h5>Low Angle</h5>
                      <p>Creates powerful, eye-level animal portraits</p>
