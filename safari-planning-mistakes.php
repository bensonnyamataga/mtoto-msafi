                <td>6-8 weeks before</td>
                <td>Visit travel clinic for vaccinations and malaria prophylaxis</td>
              </tr>
              <tr>
                <td>4 weeks before</td>
                <td>Purchase travel insurance with medical evacuation coverage</td>
              </tr>
              <tr>
                <td>2 weeks before</td>
                <td>Prepare first aid kit and gather prescription medications</td>
              </tr>
              <tr>
                <td>1 week before</td>
                <td>Confirm all documents (passport, visas, certificates)</td>
              </tr>
              <tr>
                <td>Day of travel</td>
                <td>Pack health essentials in carry-on, including motion sickness remedies</td>
