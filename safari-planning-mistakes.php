        <h2 class="tab-title">Mistake 5: Underestimating Travel Times Between Parks</h2>
        <p>Tanzania's vast wilderness areas require significant travel time that many itineraries don't adequately account for. Road conditions vary greatly between paved highways and rough park tracks, making estimated arrival times unpredictable.</p> <br>
        
        <p>The drive from Arusha to Serengeti can take 8+ hours depending on stops and wildlife sightings along the way. Many travelers mistakenly schedule international flights too close to their safari start/end dates without allowing for these transit times.</p>
        
        <div class="card solution-card mt-4">
          <div class="card-body">
            <h5>Solution: Realistic Travel Planning</h5>
            <ul>
              <li>Limit to 2-3 parks for a 7-10 day safari to minimize transit days</li>
              <li>Consider domestic flights between distant locations (but check luggage limits)</li>
              <li>Schedule international flights with buffer days before/after safari</li>
              <li>Account for wildlife viewing opportunities during transfers</li>
              <li>Verify road conditions with your operator during rainy seasons</li>
            </ul>
          </div>
        </div>

        <h2 class="tab-title">Mistake 6: Choosing the Wrong Accommodation Type</h2>
        <p>Selecting lodges based solely on price or luxury level without considering location can significantly impact your wildlife experience. Many travelers don't realize that being inside a park versus outside the gates affects both game viewing opportunities and overall safari atmosphere.</p>  <br>
        
        <p>Permanent lodges offer more amenities but are often situated outside park boundaries, requiring daily drives to reach prime viewing areas. Tented camps provide more authentic experiences and better locations but with fewer comforts. Luxury camps combine the best of both but at premium prices.</p>
        
        <div class="card solution-card mt-4">
          <div class="card-body">
            <h5>Solution: Strategic Accommodation Selection</h5>
            <div class="season-grid">
              <div class="season-item">
                <i class="fas fa-map-marker-alt"></i>
                <p>For prime wildlife access: Choose camps inside the parks</p>
              </div>
              <div class="season-item">
                <i class="fas fa-money-bill-wave"></i>
                <p>For budget travelers: Lodges outside park gates offer best value</p>
              </div>
              <div class="season-item">
                <i class="fas fa-users"></i>
                <p>For families: Larger lodges with pools and activities</p>
              </div>
              <div class="season-item">
                <i class="fas fa-camera"></i>
                <p>For photographers: Mobile camps that follow wildlife movements</p>
              </div>
            </div>
