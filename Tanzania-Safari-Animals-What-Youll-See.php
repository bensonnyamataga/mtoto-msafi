                <!-- Section 1: The Big 5 -->
                <h2 class="tab-title">1. The Legendary Big 5 Animals of Tanzania</h2>
                <div class="tour-plan">
                  <p class="tp-text">Originally named by hunters as Africa's most dangerous animals to hunt, today spotting the Big 5 is the highlight of any Tanzania safari:</p>
                  
                  <h4 class="tp-title"><i class="fas fa-lion"></i> Lions - Kings of the Savanna</h4>
                  <p class="tp-text">Tanzania has approximately 15,000 lions - about 40% of Africa's total population. The Serengeti's prides can number up to 30 individuals. Unique behaviors to watch for:</p>
                  <ul class="tp-list">
                    <li><strong>Tree-climbing lions:</strong> Only found regularly in Lake Manyara and Queen Elizabeth NP (Uganda)</li>
                    <li><strong>Hunting strategies:</strong> Females hunt cooperatively at dawn/dusk</li>
                    <li><strong>Cub rearing:</strong> June-August is best for seeing playful cubs</li>
                  </ul>
                  <img src="assets/img/serengeti-lion-pride.jpg" alt="Lion pride in Serengeti National Park" class="img-fluid">
                  <p class="img-caption">A lion pride rests in the Serengeti (Photo: Jarga Tours)</p>

                  <h4 class="tp-title"><i class="fas fa-cat"></i> Leopards - The Elusive Phantom</h4>
                  <p class="tp-text">The most challenging Big 5 animal to spot due to their solitary nature and camouflage. Prime viewing areas:</p>
                  <ul class="tp-list">
                    <li><strong>Seronera River (Serengeti):</strong> Highest leopard density in Africa</li>
                    <li><strong>Tarangire's Silale Swamp:</strong> Look for them draped over sausage trees</li>
                    <li><strong>Best time:</strong> Early morning when they're active</li>
                  </ul>
                </div>

                <!-- Section 2: Rare Species -->
                <h2 class="tab-title">2. Rare & Unique Animals in Tanzania</h2>
                <div class="tour-plan">
                  <h4 class="tp-title"><i class="fas fa-tree"></i> Tree-Climbing Lions of Lake Manyara</h4>
                  <p class="tp-text">While lions typically rest on the ground, Lake Manyara's lions climb fig trees daily. Scientists believe this adaptation helps them:</p>
                  <ul class="tp-list">
                    <li>Escape biting tsetse flies on the ground</li>
                    <li>Enjoy cooler breezes above the heat</li>
                    <li>Survey the plains for prey</li>
                  </ul>
                  <img src="assets/img/tree-climbing-lions-manyara.jpg" alt="Tree-climbing lions in Lake Manyara" class="img-fluid">
                  
                  <h4 class="tp-title"><i class="fas fa-hippo"></i> Endangered Species</h4>
                  <div class="row">
                    <div class="col-md-6">
                      <h5>Black Rhino</h5>
                      <p>Fewer than 100 remain in Tanzania. Ngorongoro Crater offers the best sightings (usually near Lerai Forest).</p>
                    </div>
                    <div class="col-md-6">
                      <h5>African Wild Dog</h5>
                      <p>Only 1,400 left in Tanzania. Selous Game Reserve is your best bet (60% of population).</p>
                    </div>
                  </div>
                </div>

                <!-- Section 3: Birdlife -->
                <h2 class="tab-title">3. Tanzania's Spectacular Birdlife</h2>
                <div class="tour-plan">
                  <p class="tp-text">With over 1,100 species, Tanzania is a birder's paradise. Highlights include:</p>
                  
                  <div class="row">
                    <div class="col-md-4">
                      <h5><i class="fas fa-dove"></i> Flamingos</h5>
                      <p>Lake Natron hosts 2.5 million lesser flamingos during breeding season (Aug-Oct).</p>
                    </div>
                    <div class="col-md-4">
                      <h5><i class="fas fa-kiwi-bird"></i> Endemic Species</h5>
                      <p>Tanzania has 32 endemic birds including the Udzungwa partridge and rufous-winged sunbird.</p>
                    </div>
                    <div class="col-md-4">
                      <h5><i class="fas fa-feather-alt"></i> Raptors</h5>
                      <p>Look for martial eagles (Africa's largest) and bateleur eagles in Tarangire.</p>
                    </div>
                  </div>
                  <img src="assets/img/tanzania-flamingos.jpg" alt="Flamingos in Lake Natron Tanzania" class="img-fluid">
                </div>

